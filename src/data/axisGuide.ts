// 변동값(diff)으로 방향 판정. 임계값 2 (펜타곤과 동일 기준).
export function dirFromDiff(diff: number): ChangeDir {
  if (diff <= -2) return 'down';
  if (diff >= 2) return 'up';
  return 'flat';
}

